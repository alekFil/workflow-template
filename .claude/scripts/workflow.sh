#!/bin/bash
# Workflow helper: generated views over decisions and task cards.
#
#   workflow.sh adr-index   regenerate <DECISIONS_DIR>/README.md from ADR frontmatter
#   workflow.sh tasks       list open task cards (in-progress first, then by priority)
#   workflow.sh tasks --all also list rejected cards
#   workflow.sh done        list closed tasks from "Closes-Task:" commit trailers
#   workflow.sh bootstrap   devmeta profiles: clone the code repository into
#                           CODE_DIR, add the upstream remote, install the leak guard
#
# Settings come from .claude/workflow.conf (shell syntax) at the repository root.
# Generated files are never edited by hand: on a merge conflict, rerun the command.
set -euo pipefail

ROOT=$(git rev-parse --show-toplevel)
cd "$ROOT"

PROFILE="project"
CODE_DIR="."
CODE_REPO=""
UPSTREAM_REPO=""
DECISIONS_DIR="docs/decisions"
TASKS_DIR=".context/tasks"
# shellcheck disable=SC1091
[ -f .claude/workflow.conf ] && . .claude/workflow.conf

# Print one frontmatter field of a markdown file (empty if absent).
field() {
    awk -v key="$2" '
        NR == 1 && $0 == "---" { inside = 1; next }
        inside && $0 == "---" { exit }
        inside {
            k = $0; sub(/:.*/, "", k)
            if (k == key) {
                v = $0; sub(/^[^:]*:[ ]*/, "", v)
                gsub(/^"|"$/, "", v)
                print v; exit
            }
        }' "$1"
}

adr_index() {
    if [ "$DECISIONS_DIR" = "none" ]; then
        echo "Decisions are not kept in this project (DECISIONS_DIR=none)."
        return 0
    fi
    mkdir -p "$DECISIONS_DIR"
    local out="$DECISIONS_DIR/README.md" active="" archived="" legacy=0 f id title status date ref sup
    for f in $(ls -r "$DECISIONS_DIR"/*.md 2>/dev/null | grep -v '/README\.md$' || true); do
        [ -n "$(field "$f" legacy-id)" ] && legacy=1
    done
    for f in $(ls -r "$DECISIONS_DIR"/*.md 2>/dev/null | grep -v '/README\.md$' || true); do
        id=$(basename "$f" .md)
        title=$(field "$f" title)
        status=$(field "$f" status)
        date=$(field "$f" date)
        ref=$(field "$f" legacy-id)
        sup=$(field "$f" superseded-by)
        if [ "$status" = "accepted" ]; then
            if [ "$legacy" = 1 ]; then
                active+="| $date | [$title]($id.md) | ${ref:-–} |"$'\n'
            else
                active+="| $date | [$title]($id.md) |"$'\n'
            fi
        else
            [ -n "$sup" ] && sup="[$sup]($sup.md)"
            archived+="| $date | [$title]($id.md) | $status | ${sup:-–} |"$'\n'
        fi
    done
    {
        echo "# Architecture decisions"
        echo ""
        echo "<!-- Generated by .claude/scripts/workflow.sh adr-index. Do not edit by hand. -->"
        echo ""
        echo "One file per decision: \`YYYY-MM-DD-<slug>.md\`. New decisions – \`/record\`."
        echo ""
        echo "## Active"
        echo ""
        if [ "$legacy" = 1 ]; then
            echo "| Date | Decision | Former number |"
            echo "| --- | --- | --- |"
        else
            echo "| Date | Decision |"
            echo "| --- | --- |"
        fi
        printf "%s" "$active"
        if [ -n "$archived" ]; then
            echo ""
            echo "## Superseded and rejected"
            echo ""
            echo "| Date | Decision | Status | Replaced by |"
            echo "| --- | --- | --- | --- |"
            printf "%s" "$archived"
        fi
    } > "$out"
    echo "Index updated → $out"
}

tasks() {
    local all="${1:-}" f slug title status prio rows=""
    for f in "$TASKS_DIR"/*.md; do
        [ -e "$f" ] || continue
        slug=$(basename "$f" .md)
        title=$(field "$f" title)
        status=$(field "$f" status)
        prio=$(field "$f" priority)
        case "$status" in
            in-progress) rows+="0|${prio:-9}|$status|$slug|$title"$'\n' ;;
            next) rows+="1|${prio:-9}|$status|$slug|$title"$'\n' ;;
            rejected) [ "$all" = "--all" ] && rows+="2|${prio:-9}|$status|$slug|$title"$'\n' ;;
        esac
    done
    if [ -z "$rows" ]; then
        echo "No open tasks in $TASKS_DIR."
        return 0
    fi
    echo "| Priority | Status | Task | Title |"
    echo "| --- | --- | --- | --- |"
    printf "%s" "$rows" | sort -t'|' -k1,1n -k2,2n -k4,4 \
        | awk -F'|' '{ printf "| %s | %s | %s | %s |\n", $2, $3, $4, $5 }'
}

done_tasks() {
    # Closed tasks are recorded as "Closes-Task: <slug>" trailers in the commit that
    # deletes the card (in the context repository).
    git log --date=short --format='%h %ad %(trailers:key=Closes-Task,valueonly,separator=%x2C)' \
        | awk 'NF >= 3'
}

bootstrap() {
    if [ "$CODE_DIR" = "." ]; then
        echo "Profile \"$PROFILE\" keeps code in this repository – nothing to do."
        return 0
    fi
    if [ ! -d "$CODE_DIR/.git" ]; then
        if [ -z "$CODE_REPO" ]; then
            echo "CODE_REPO is empty in .claude/workflow.conf – clone the code into $CODE_DIR manually."
            return 1
        fi
        git clone "$CODE_REPO" "$CODE_DIR"
    fi
    if [ -n "$UPSTREAM_REPO" ] && ! git -C "$CODE_DIR" remote get-url upstream &>/dev/null; then
        git -C "$CODE_DIR" remote add upstream "$UPSTREAM_REPO"
        git -C "$CODE_DIR" fetch upstream
    fi
    # The code repository must never receive workflow files. The hook lives in
    # .git/hooks of the code repository, so it is not committed and not pushed.
    local hook="$CODE_DIR/.git/hooks/pre-commit"
    cat > "$hook" <<'HOOK'
#!/bin/bash
# Installed by .claude/scripts/workflow.sh bootstrap (workflow-template devmeta).
# Blocks workflow files from entering this code repository.
# Override for a deliberate change: WT_ALLOW_WORKFLOW_FILES=1 git commit ...
[ "${WT_ALLOW_WORKFLOW_FILES:-}" = "1" ] && exit 0
leaked=$(git diff --cached --name-only | grep -E '^(CLAUDE\.md|WORKFLOW\.md|\.claude/|\.context/)' || true)
if [ -n "$leaked" ]; then
    echo "pre-commit: workflow files must stay in the devmeta repository:"
    echo "$leaked" | sed 's/^/  /'
    exit 1
fi
HOOK
    chmod +x "$hook"
    echo "Code repository ready → $CODE_DIR (leak guard: $hook)"
}

case "${1:-}" in
    adr-index) adr_index ;;
    tasks) tasks "${2:-}" ;;
    done) done_tasks ;;
    bootstrap) bootstrap ;;
    *)
        sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
        exit 1
        ;;
esac
